    def test_non_orphaned_items_still_present_with_original_index(self):
        visible_by_pair = {(item["brand"], item["name"]): item for item in prices_state.visible_flat_items()}
        self.assertIn(("نابولي", "نابولي قصير دهبي"), visible_by_pair)
        self.assertIn(("ون شيستر", "ون شيستر كوين فضي"), visible_by_pair)
        self.assertIn(("جيتان", "جيتان قصير"), visible_by_pair)
        # الفهرس (index) ما تغير — لسا نفس رقمه الأصلي بملف price_sheet.json.
        self.assertEqual(visible_by_pair[("جيتان", "جيتان قصير")]["index"], 0)
        # صنف "ماستر" الجديد (المضاف بآخر price_sheet.json) ظاهر برقمه الجديد.
        self.assertEqual(visible_by_pair[("ماستر", "ماستر طويل")]["index"], 579)
        # صنف "تيرا تركواز" الجديد (المضاف بآخر price_sheet.json) ظاهر برقمه الجديد.
        self.assertIn(("تيرا", "تيرا تركواز"), visible_by_pair)
        self.assertEqual(visible_by_pair[("تيرا", "تيرا تركواز")]["index"], 580)
        # صنف "مادوكس" الجديد (المضاف لماركة "كابتن بلاك" بآخر price_sheet.json) ظاهر برقمه الجديد.
        self.assertIn(("كابتن بلاك", "مادوكس"), visible_by_pair)
        self.assertEqual(visible_by_pair[("كابتن بلاك", "مادوكس")]["index"], 581)
        # أول ٤ ماركات جوا القسم الجديد "دخان وزاري": الصنف العام تبع كل
        # وحدة منهن انحذف بعدين (مالبورو/كينت/ونستون/دفيدوف) — orphans، شوف فوق.
        self.assertNotIn(("مالبورو", "مالبورو"), visible_by_pair)
        self.assertNotIn(("كينت", "كينت"), visible_by_pair)
        self.assertNotIn(("ونستون", "ونستون"), visible_by_pair)
        self.assertNotIn(("دفيدوف", "دفيدوف"), visible_by_pair)
        # ٤ أصناف مفصّلة جداد جوا ماركة "دفيدوف" ظاهرين بأرقامهن الجديدة.
        for i, name in enumerate(["دفيدوف دهبي عريض", "دفيدوف ابيض عريض", "دفيدوف خمري عريض", "دفيدوف سليم"]):
            self.assertIn(("دفيدوف", name), visible_by_pair, msg=name)
            self.assertEqual(visible_by_pair[("دفيدوف", name)]["index"], 597 + i, msg=name)
        # ٤ أصناف مفصّلة جداد جوا ماركة "مالبورو" ظاهرين بأرقامهن الجديدة.
        for i, name in enumerate(["مالبورو ابيض", "مالبورو احمر", "مالبورو كوين ازرق", "مالبورو كوين اسود"]):
            self.assertIn(("مالبورو", name), visible_by_pair, msg=name)
            self.assertEqual(visible_by_pair[("مالبورو", name)]["index"], 586 + i, msg=name)
        # صنفين مفصّلين جداد جوا ماركة "كينت" ظاهرين بأرقامهن الجديدة.
        for i, name in enumerate(["كينت فضي", "كينت ازرق"]):
            self.assertIn(("كينت", name), visible_by_pair, msg=name)
            self.assertEqual(visible_by_pair[("كينت", name)]["index"], 590 + i, msg=name)
        # ٥ أصناف مفصّلة جداد جوا ماركة "ونستون" ظاهرين بأرقامهن الجديدة.
        for i, name in enumerate(["ونستون فضي", "ونستون ازرق", "ونستون احمر", "ونستون كوين ازرق", "ونستون كوين فضي"]):
            self.assertIn(("ونستون", name), visible_by_pair, msg=name)
            self.assertEqual(visible_by_pair[("ونستون", name)]["index"], 592 + i, msg=name)

